// Generates EPGMatcher's fold table (M12 step 9) from MMTVL's own normalization, so the Roku port folds names
// exactly as `EPGMatcher.normalize` (MMTVL/IPTV/EPG/EPGMatcher.swift) does on this Mac.
//
//   swift roku/tools/gen-epg-fold.swift roku/source/lib/EPGMatcher.bs roku/tests/local/support/EPGFoldFixtures.bs
//
// For every code point from U+0080 to U+FFFF, after a letter (foldAfterLetter), Swift's
//   folding(options: [.caseInsensitive, .diacriticInsensitive], locale: en_US_POSIX).lowercased()
// with each Character that isn't a letter or number turned into a space, gives one of:
//   - the code point itself: not in the table (kept as it is);
//   - a single space: a separator, stored as ranges (EPGMatcher.foldSeparators);
//   - nothing: dropped, stored as ranges (EPGMatcher.foldDrops);
//   - anything else (another letter, or several): stored as a mapping (EPGMatcher.foldMappings).
// The table replaces the text between the "generated" markers in EPGMatcher.bs. The test fixture holds Swift's
// own normalize() for "x" + <code point> + "y", for a sample of code points, so the Roku side is checked against
// MMTVL's real function rather than against the table.
import Foundation

let droppedTokens: Set<String> = ["hd", "fhd", "uhd", "sd", "4k", "hevc"]

// MMTVL's EPGMatcher.rawTokens, as written there.
func rawTokens(_ name: String) -> [String] {
    let folded = name
        .folding(options: [.caseInsensitive, .diacriticInsensitive], locale: Locale(identifier: "en_US_POSIX"))
        .lowercased()
        .replacingOccurrences(of: "&", with: " and ")
        .replacingOccurrences(of: "+", with: " plus ")
    return folded
        .split { !($0.isLetter || $0.isNumber) }
        .map(String.init)
        .filter { !droppedTokens.contains($0) }
}

func normalize(_ name: String) -> String { rawTokens(name).joined() }

func fold(_ text: String) -> String {
    text.folding(options: [.caseInsensitive, .diacriticInsensitive], locale: Locale(identifier: "en_US_POSIX"))
        .lowercased()
        .map { ($0.isLetter || $0.isNumber) ? String($0) : " " }
        .joined()
}

func hex4(_ value: UInt32) -> String { String(format: "%04X", value) }

// How code folds after a letter, as it mostly stands in a name: a combining mark joins the letter before it into
// one Character, and Foundation's diacritic folding then drops it (alone, U+0345 would fold to ι). A code point
// that joins the next character instead (a prepended mark) folds alone.
func foldAfterLetter(_ text: String) -> String {
    let joined = fold("x" + text)
    return joined.hasPrefix("x") ? String(joined.dropFirst()) : fold(text)
}

extension Array where Element == (UInt32, UInt32) {
    mutating func append(range code: UInt32) {
        if let last = self.last, last.1 == code - 1 {
            self[count - 1].1 = code
        } else {
            append((code, code))
        }
    }
}

var separators: [(UInt32, UInt32)] = []
var drops: [(UInt32, UInt32)] = []
var mappings: [String] = []
for code in UInt32(0x80)...0xFFFF {
    guard let scalar = Unicode.Scalar(code) else { continue }
    let text = String(Character(scalar))
    let out = foldAfterLetter(text)
    if out == text { continue }
    if out == " " || out.isEmpty {
        if out.isEmpty {
            drops.append(range: code)
        } else {
            separators.append(range: code)
        }
        continue
    }
    let scalars = Array(out.unicodeScalars)
    precondition(scalars.count <= 9 && scalars.allSatisfy { $0.value <= 0xFFFF }, "U+\(hex4(code)) folds to \(out)")
    mappings.append(hex4(code) + String(scalars.count) + scalars.map { hex4($0.value) }.joined())
}

func chunked(_ text: String, _ width: Int) -> [String] {
    var lines: [String] = []
    var rest = Substring(text)
    while !rest.isEmpty {
        lines.append(String(rest.prefix(width)))
        rest = rest.dropFirst(width)
    }
    return lines
}

func function(_ name: String, _ comment: String, _ text: String) -> String {
    var lines = ["    ' \(comment)", "    function \(name)() as string"]
    let parts = chunked(text, 96)
    for (index, part) in parts.enumerated() {
        lines.append(index == 0 ? "        table = \"\(part)\"" : "        table += \"\(part)\"")
    }
    if parts.isEmpty { lines.append("        table = \"\"") }
    lines.append("        return table")
    lines.append("    end function")
    return lines.joined(separator: "\n")
}

let begin = "    ' --- Generated by tools/gen-epg-fold.swift; don't edit by hand. ---"
let end = "    ' --- End of generated code. ---"
let generated = [
    begin,
    "",
    function("foldSeparators",
             "Separator ranges, 8 hex digits each (first, last): \(separators.count) ranges.",
             separators.map { hex4($0.0) + hex4($0.1) }.joined()),
    "",
    function("foldDrops",
             "Dropped ranges (combining marks after a letter), 8 hex digits each (first, last): \(drops.count) ranges.",
             drops.map { hex4($0.0) + hex4($0.1) }.joined()),
    "",
    function("foldMappings",
             "Mappings: 4 hex digits (the code point), a count, then that many 4-digit code points: \(mappings.count).",
             mappings.joined()),
    "",
    end,
].joined(separator: "\n")

let arguments = CommandLine.arguments
guard arguments.count == 3 else {
    FileHandle.standardError.write("Usage: swift gen-epg-fold.swift <EPGMatcher.bs> <EPGFoldFixtures.bs>\n".data(using: .utf8)!)
    exit(2)
}

let libURL = URL(fileURLWithPath: arguments[1])
let lib = try String(contentsOf: libURL, encoding: .utf8)
guard let beginRange = lib.range(of: begin), let endRange = lib.range(of: end), beginRange.upperBound <= endRange.lowerBound else {
    FileHandle.standardError.write("The generated markers aren't in \(arguments[1])\n".data(using: .utf8)!)
    exit(1)
}
try (lib[..<beginRange.lowerBound] + generated + lib[endRange.upperBound...]).write(to: libURL, atomically: true, encoding: .utf8)

// Samples: every code point in the Latin, Greek and Cyrillic ranges and Latin Extended Additional, every 7th
// elsewhere in the BMP (no surrogates). Each entry is Swift's normalize("x" + c + "y") between the x and y,
// when that isn't c itself.
var samples: [UInt32] = []
for code in UInt32(0x80)...0xFFFF {
    if (0xD800...0xDFFF).contains(code) { continue }
    if code <= 0x52F || (0x1E00...0x1EFF).contains(code) || code % 7 == 0 { samples.append(code) }
}
var expected: [String] = []
var contextual: [UInt32] = []
for code in samples {
    let scalar = Unicode.Scalar(code)!
    let result = normalize("x" + String(Character(scalar)) + "y")
    // A prepended concatenation mark (U+0600…) joins the "y" into one Character: grapheme context the table
    // can't hold. Such code points are left out of the samples and listed.
    guard result.hasPrefix("x"), result.hasSuffix("y") else {
        contextual.append(code)
        continue
    }
    let middle = String(result.dropFirst().dropLast())
    if middle == String(Character(scalar)) { continue }
    let scalars = Array(middle.unicodeScalars)
    expected.append(hex4(code) + String(scalars.count) + scalars.map { hex4($0.value) }.joined())
}
let fixture = [
    "' Generated by tools/gen-epg-fold.swift from MMTVL's EPGMatcher.normalize on this Mac; don't edit by hand.",
    "' Samples: every code point from U+0080 to U+052F and U+1E00 to U+1EFF, and every 7th elsewhere in the BMP",
    "' (EPGMatcherTests.isSample).",
    "' Each entry: 4 hex digits (the code point), a count, then that many code points: normalize(\"x\" + c + \"y\")",
    "' between the x and the y, for each sampled c where that isn't c itself (\(expected.count) of \(samples.count)).",
    "' Left out, since Swift joins them with the next character: \(contextual.map { "U+" + hex4($0) }.joined(separator: " ")).",
    "namespace EPGFoldFixtures",
    "",
    function("expected", "Swift's results.", expected.joined()),
    "",
    function("contextual", "The code points left out, 4 hex digits each.", contextual.map(hex4).joined()),
    "",
    "end namespace",
    "",
].joined(separator: "\n")
try fixture.write(to: URL(fileURLWithPath: arguments[2]), atomically: true, encoding: .utf8)
print("Separators: \(separators.count) ranges; drops: \(drops.count) ranges; mappings: \(mappings.count); samples: \(samples.count), \(expected.count) differ")
